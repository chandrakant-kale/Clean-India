// Helper Functions

export const getStates = () => locationData.states;

export const getDistricts = (stateId) => {
  const state = locationData.states.find(s => s.id === stateId);
  return state ? state.districts : [];
};

export const getTalukas = (stateId, districtId) => {
  const state = locationData.states.find(s => s.id === stateId);
  if (!state) return [];

  const district = state.districts.find(d => d.id === districtId);
  return district ? district.talukas : [];
};

export const getVillages = (stateId, districtId, talukaId) => {
  const state = locationData.states.find(s => s.id === stateId);
  if (!state) return [];

  const district = state.districts.find(d => d.id === districtId);
  if (!district) return [];

  const taluka = district.talukas.find(t => t.id === talukaId);
  return taluka ? taluka.villages : [];
};